// Writes app/version.ts from the published package, so the page always names the version that is on npm.
import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { fileURLToPath, URL } from 'node:url'

const read = (path) => fileURLToPath(new URL(path, import.meta.url))
const { version } = JSON.parse(readFileSync(read('../../packages/tessera/package.json'), 'utf8'))
const [major, minor] = version.split('.')

writeFileSync(
  read('../app/version.ts'),
  `// Generated by scripts/version.mjs from packages/tessera/package.json. Do not edit.
export const VERSION = '${version}'
export const SHORT_VERSION = 'v${major}.${minor}'
`,
)
process.stdout.write(`app/version.ts: ${version}
`)
