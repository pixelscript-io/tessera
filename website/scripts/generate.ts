/**
 * Writes the reference pages that must not be maintained by hand: the error reference (from the error
 * registry), the CLI reference (from the command definitions), the config reference (from the TSDoc of
 * `TesseraConfig`), the contract reference (from the JSON schema), the token format reference (from the tokens
 * package) and the API reference (from the TSDoc of each package's exports). Run by `pnpm --filter website
 * generate`, which `dev` and `build` do first.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  ALL_CODES,
  CODE_GROUPS,
  EXPLANATIONS,
  exampleSource,
  runExample,
  type ExampleEnv,
} from '@tessera/compiler'
import { loadDesignTokens } from '@tessera/compiler/project'
import { TOOLS } from '@tessera/agent'
import { COMMANDS_DOC, GLOBAL_OPTIONS } from '@tessera/cli'
import { contractSchema } from '@tessera/contract'
import { buildTokens, SUPPORTED_TYPES } from '@tessera/tokens'
import { loadTokenDir } from '@tessera/tokens/node'
import { documentExports, documentInterface } from './tsdoc'

const here = dirname(fileURLToPath(import.meta.url))
const repo = join(here, '..', '..')
const out = join(here, '..', 'content', 'reference')

const BANNER = '<!-- Generated by website/scripts/generate.ts. Do not edit. -->\n\n'

const write = (file: string, content: string) => {
  const path = join(out, file)
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, BANNER + content.trimEnd() + '\n')
}

/** Text that is safe in Markdown that Vue compiles: a bare `<` outside code is escaped. */
const safe = (text: string) =>
  text
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replaceAll('<', '&lt;').replaceAll('{', '&#123;')))
    .join('')

const cell = (text: string) =>
  safe(text)
    .replaceAll('|', '\\|')
    .replace(/\s*\n\s*/g, ' ')
const code = (text: string) => '`' + text.replaceAll('|', '\\|') + '`'

/** The site is themed by Tessera's own tokens: write their CSS where the theme imports it. */
function themeTokens() {
  const built = buildTokens(loadTokenDir(join(repo, 'system', 'tokens')))
  if (!built.ok) throw new Error('The repository tokens do not build.')
  const path = join(here, '..', 'content', '.vitepress', 'theme', 'tokens.css')
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(
    path,
    '/* Generated by website/scripts/generate.ts from system/tokens. Do not edit. */\n' + built.css,
  )
}

// --- errors ---------------------------------------------------------------------------------------------

function errors() {
  rmSync(join(out, 'errors'), { recursive: true, force: true })
  const loaded = loadDesignTokens(join(repo, 'system', 'tokens'))
  if (!loaded.ok) throw new Error('The repository tokens do not build.')
  const env: ExampleEnv = {
    tokens: loaded.tokens,
    button: readFileSync(join(repo, 'system', 'components', 'Button.tess'), 'utf8'),
    link: readFileSync(join(repo, 'packages', 'router', 'components', 'Link.tess'), 'utf8'),
  }

  const codes = Object.keys(ALL_CODES).sort()
  for (const c of codes) {
    const e = EXPLANATIONS[c]
    if (!e) throw new Error(`${c} has no explanation in packages/compiler/src/explanations.ts`)
    const title = ALL_CODES[c]!
    const output = runExample(e.example, env)
    const message = output.messages.find((m) => m.includes(` ${c} `)) ?? output.messages[0]
    const source = exampleSource(e.example).trimEnd()
    const options = e.example.kind === 'tess' ? e.example.options : undefined
    // The checker compiles a sample with the project's own settings, so an example that needs others is shown as text.
    const needsOptions =
      (!!options && (options.autoImports !== undefined || options.contract !== undefined)) ||
      (e.example.kind === 'tess' && (!!e.example.components || !!e.example.deprecatedTokens))
    const fence =
      e.example.kind === 'tess' && !needsOptions
        ? `xml tess error=${c} file=${e.example.file}`
        : e.example.kind === 'ts'
          ? 'ts'
          : 'text'
    const lines = [
      `# ${c}: ${safe(title)}`,
      '',
      '## Cause',
      '',
      safe(e.cause),
      '',
      '## Example',
      '',
      '```' + fence,
      source,
      '```',
      '',
      '## What you see',
      '',
      '```text',
      message ?? '',
      '```',
      '',
      '## Fix',
      '',
      safe(e.fix),
    ]
    if (e.fixed) lines.push('', '```text', e.fixed, '```')
    lines.push('', '[All errors and warnings](/reference/errors/)')
    write(`errors/${c}.md`, lines.join('\n'))
  }

  const index = [
    '# Errors and warnings',
    '',
    `Every code Tessera can report, ${codes.length} in all. Each page has the cause, an example that produces it (checked by the test suite, and the message shown is the real one) and the fix. \`tessera explain <code>\` prints the same text in the terminal.`,
    '',
  ]
  for (const group of CODE_GROUPS) {
    const members = codes.filter((c) => group.test(c))
    if (!members.length) continue
    index.push(`## ${group.title}`, '')
    for (const c of members) index.push(`- [${c}](/reference/errors/${c}): ${safe(ALL_CODES[c]!)}`)
    index.push('')
  }
  write('errors/index.md', index.join('\n'))
}

// --- CLI ------------------------------------------------------------------------------------------------

function cli() {
  const lines = [
    '# CLI reference',
    '',
    'Every `tessera` command. Each runs in the nearest folder above the current one that looks like a project, or the one named with `--root`. See [The command line](/guide/cli) for how they fit together.',
    '',
    '## Options for every command',
    '',
    ...GLOBAL_OPTIONS.map((o) => `- ${code(o.flag)}: ${safe(o.description)}`),
    '',
  ]
  for (const c of COMMANDS_DOC) {
    lines.push(`## ${c.name}`, '', '```bash', c.usage, '```', '', safe(c.details), '')
    if (c.options?.length) {
      lines.push('| Option | |', '| --- | --- |')
      for (const o of c.options) lines.push(`| ${code(o.flag)} | ${cell(o.description)} |`)
      lines.push('')
    }
  }
  lines.push(
    'Exit codes: `0` on success, `1` on any error, with the message printed to standard error.',
  )
  write('cli.md', lines.join('\n'))
}

// --- MCP tools ------------------------------------------------------------------------------------------

function mcpTools() {
  const lines = [
    '# MCP server reference',
    '',
    'The tools `tessera mcp` offers an AI client. All of them are read-only. See [AI coding tools](/guide/agents) for how to connect a client.',
    '',
  ]
  for (const tool of TOOLS) {
    lines.push(`## ${tool.name}`, '', safe(tool.description), '')
    const props = Object.entries(tool.inputSchema.properties)
    if (props.length) {
      lines.push('| Argument | Type | |', '| --- | --- | --- |')
      for (const [name, p] of props) {
        const required = tool.inputSchema.required?.includes(name) ? ' Required.' : ''
        lines.push(`| ${code(name)} | ${p.type} | ${cell(p.description)}${required} |`)
      }
      lines.push('')
    } else lines.push('No arguments.', '')
  }
  write('mcp.md', lines.join('\n'))
}

// --- config ---------------------------------------------------------------------------------------------

function config() {
  const entry = join(repo, 'packages', 'compiler', 'src', 'index.ts')
  const main = documentInterface(entry, 'TesseraConfig')
  const rule = documentInterface(entry, 'SeverityRule')
  const accept = documentInterface(entry, 'Accept')
  const table = (members: ReturnType<typeof documentInterface>['members']) => [
    '| Field | Type | |',
    '| --- | --- | --- |',
    ...members.map(
      (m) =>
        `| ${code(m.name + (m.optional ? '?' : ''))} | ${code(m.type)} | ${cell(m.doc || 'Not documented yet.')} |`,
    ),
  ]
  write(
    'config.md',
    [
      '# tessera.config.ts',
      '',
      'The config file at the project root. Its default export is an object with the fields below. The Vite plugin and the CLI both read it, so a build and `tessera check` agree. Options passed to `tessera()` in `vite.config.ts` win over the file.',
      '',
      '```ts',
      "import { defineConfig } from '@tessera/compiler'",
      '',
      'export default defineConfig({',
      "  severity: [{ files: 'app/legacy/**', rules: '*', level: 'warn', reason: 'old screens', expires: '2027-03-01' }],",
      '})',
      '```',
      '',
      '## Style and project fields',
      '',
      ...table(main.members),
      '',
      'The file may also set `contracts` (`"required"` or `"optional"`, to relax the contract requirement for `app/components`), `tokens` (the tokens folder), `baseline` (the baseline file) and `today` (a date, for tests). These three take paths relative to the project.',
      '',
      '## severity',
      '',
      ...table(rule.members),
      '',
      'A rule set to `warn` or `off` needs a `reason`; after `expires` it is an error again ([T2112](/reference/errors/T2112) if it is malformed).',
      '',
      '## governed',
      '',
      'Each entry maps a CSS property to what it accepts instead of a raw value, or `false` to stop governing it.',
      '',
      ...table(accept.members),
    ].join('\n'),
  )
}

// --- contract -------------------------------------------------------------------------------------------

function contract() {
  const schema = contractSchema as unknown as {
    required: string[]
    properties: Record<string, { type?: string; enum?: string[]; description?: string }>
  }
  const lines = [
    '# Contract reference',
    '',
    'The `<contract>` block is JSON (comments and trailing commas allowed). This page is generated from the contract JSON Schema, which editors can use too. See [Contracts](/guide/contracts) for the ideas behind it.',
    '',
    '| Field | Type | Required | |',
    '| --- | --- | --- | --- |',
  ]
  for (const [name, prop] of Object.entries(schema.properties)) {
    const type = prop.enum ? `one of ${prop.enum.length} values` : (prop.type ?? 'object')
    lines.push(
      `| ${code(name)} | ${type} | ${schema.required.includes(name) ? 'yes' : 'no'} | ${cell(prop.description ?? '')} |`,
    )
  }
  const roles = schema.properties.role?.enum
  if (roles) lines.push('', '## Roles', '', roles.map(code).join(', '))
  write('contract.md', lines.join('\n'))
}

