const TYPE_SHAPES: Record<string, { value: string; css: string }> = {
  color: { value: '{ "colorSpace": "srgb", "components": [0.145, 0.388, 0.922] }', css: 'a color' },
  dimension: { value: '{ "value": 16, "unit": "px" }', css: '16px (units px and rem)' },
  duration: { value: '{ "value": 150, "unit": "ms" }', css: '150ms (units ms and s)' },
  number: { value: '0.5', css: 'a number' },
  fontFamily: { value: '["Inter", "system-ui", "sans-serif"]', css: 'a font-family list' },
  fontWeight: { value: '600', css: 'a number from 1 to 1000, or a name such as "bold"' },
  cubicBezier: { value: '[0.2, 0, 0, 1]', css: 'cubic-bezier(0.2, 0, 0, 1)' },
  strokeStyle: { value: '"dashed"', css: 'the string form' },
  shadow: {
    value:
      '{ "color": "{color.shadow}", "offsetX": ..., "offsetY": ..., "blur": ..., "spread": ... }',
    css: 'a box-shadow',
  },
  border: {
    value: '{ "color": "...", "width": "...", "style": "solid" }',
    css: 'a border shorthand',
  },
  transition: {
    value: '{ "duration": "...", "delay": "...", "timingFunction": "..." }',
    css: 'a transition shorthand',
  },
}

function tokens() {
  for (const type of SUPPORTED_TYPES) {
    if (!TYPE_SHAPES[type])
      throw new Error(`website/scripts/generate.ts has no shape for the token type ${type}`)
  }
  write(
    'tokens.md',
    [
      '# Token format reference',
      '',
      'Tokens are strict [DTCG](https://www.designtokens.org/) 2025.10 JSON in `*.tokens.json` files, compiled to CSS custom properties in `@layer tessera.tokens`. See [Tokens](/guide/tokens) for how they are organized and themed.',
      '',
      '## Supported types',
      '',
      '| `$type` | `$value` | Becomes |',
      '| --- | --- | --- |',
      ...SUPPORTED_TYPES.map(
        (t) => `| ${code(t)} | ${code(TYPE_SHAPES[t]!.value)} | ${cell(TYPE_SHAPES[t]!.css)} |`,
      ),
      '',
      'Anything else (a gradient, a typography composite) is reported as [T1004](/reference/errors/T1004) rather than ignored. Unsupported DTCG features such as group `$extends` and `$ref` are [T1009](/reference/errors/T1009).',
      '',
      '## Names',
      '',
      'A token path becomes a custom property: `space.4` is `--t-space-4`, `color.action.primary.bg` is `--t-color-action-primary-bg`. Names use letters, numbers, `-` and `_` ([T1002](/reference/errors/T1002)).',
      '',
      '## Tiers',
      '',
      'Each token is a primitive, semantic or component token (`$extensions.tessera.tier`, inheritable from a group). Components should use semantic tokens; using a primitive is [T2105](/reference/errors/T2105).',
      '',
      '## Theme files',
      '',
      'A file in `themes/` overrides values of existing tokens. `"$extends"` names the base, `"$attribute"` the HTML attribute (default `theme`) and `"$auto"` an optional media feature. A theme cannot add a token or change a type ([T1011](/reference/errors/T1011), [T1012](/reference/errors/T1012)).',
      '',
      "## This repository's tokens",
      '',
      'The design system in `system/tokens`, as `tessera tokens build` reports it.',
      '',
      ...tokenRows(),
    ].join('\n'),
  )
}

function tokenRows(): string[] {
  const built = buildTokens(loadTokenDir(join(repo, 'system', 'tokens')))
  if (!built.ok) throw new Error('The repository tokens do not build.')
  return [
    '| Token | Type | Tier |',
    '| --- | --- | --- |',
    ...built.manifest!.tokens.map((t) => `| ${code(t.path)} | ${t.type} | ${t.tier} |`),
  ]
}

