function api() {
  rmSync(join(out, 'api'), { recursive: true, force: true })
  const index = [
    '# API reference',
    '',
    'Generated from the TSDoc comments in each package. An export with no description says so: that is a gap in the source comments, not in this page.',
    '',
  ]
  for (const { pkg, title, intro } of PACKAGES) {
    const exports = documentExports(join(repo, 'packages', pkg, 'src', 'index.ts'))
    const lines = [`# ${title}`, '', safe(intro), '']
    let missing = 0
    for (const e of exports) {
      if (!e.doc) missing++
      lines.push(
        `## ${e.name}`,
        '',
        `<small>${e.kind}</small>`,
        '',
        e.doc ? safe(e.doc) : '_Not documented yet._',
        '',
        '```ts',
        e.kind === 'class' ? `${e.signature} {}` : e.signature,
        '```',
        '',
      )
    }
    write(`api/${pkg}.md`, lines.join('\n'))
    index.push(
      `- [${title}](/reference/api/${pkg}): ${exports.length} exports, ${exports.length - missing} documented`,
    )
  }
  write('api/index.md', index.join('\n'))
}

