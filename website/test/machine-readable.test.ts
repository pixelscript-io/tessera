import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterAll, describe, expect, it } from 'vitest'
import { writeMachineReadable } from '../content/.vitepress/machine-readable'

const made: string[] = []
afterAll(() => made.forEach((d) => rmSync(d, { recursive: true, force: true })))

describe('llms.txt and per-page Markdown', () => {
  it('writes every page as Markdown and an index with a summary of each', () => {
    const src = mkdtempSync(join(tmpdir(), 'tessera-src-'))
    const out = mkdtempSync(join(tmpdir(), 'tessera-out-'))
    made.push(src, out)
    mkdirSync(join(src, 'guide'), { recursive: true })
    writeFileSync(join(src, 'index.md'), '---\nlayout: home\n---\n\nHello.\n')
    writeFileSync(
      join(src, 'guide', 'cli.md'),
      '# The command line\n\nRun `tessera check` to [validate](/guide/x) a project.\n\n```bash\ntessera check\n```\n',
    )
    writeFileSync(
      join(src, 'guide', 'gen.md'),
      '<!-- Generated by x. Do not edit. -->\n\n# Generated\n\nText.\n',
    )

    writeMachineReadable(src, out)

    expect(readFileSync(join(out, 'guide', 'cli.md'), 'utf8')).toContain('# The command line')
    // The generated-file banner is for maintainers, not readers.
    expect(readFileSync(join(out, 'guide', 'gen.md'), 'utf8')).not.toContain('Generated by')
    const llms = readFileSync(join(out, 'llms.txt'), 'utf8')
    expect(llms).toContain('# Tessera')
    expect(llms).toContain(
      '- [The command line](/guide/cli.md): Run tessera check to validate a project.',
    )
    expect(llms).toContain('## guide')
    expect(existsSync(join(out, 'index.md'))).toBe(true)
  })
})
