/**
 * The shared state of a project: a script file in `app/state` is shared state, named after the file (`cart.ts` is
 * `cart`), and a `.tess` script or template can use that name without importing it. What the file exports are its
 * members: signals (`state`, `derived`), functions and plain values. This is pure, so it also runs in a browser:
 * reading the folder is the caller's job (`loadProjectState` in `@tessera/compiler/node`).
 */

import { analyzeScript, type StateMemberKind, type StateMembers } from './script'

export type { StateMemberKind, StateMembers }

/** A piece of shared state that a script may name: its name, the file, and what the file exports. */
export interface ProjectState {
  name: string
  /** Absolute path. */
  file: string
  members: StateMembers
}

export interface StateDiagnostic {
  code: 'T5010'
  severity: 'error'
  /** The file, as the project shows it (`app/state/my-cart.ts`). */
  file: string
  line: number
  column: number
  message: string
  hint?: string
}

/** Names Tessera already gives a script, which a piece of state could only hide. */
const TAKEN = new Set([
  'state',
  'derived',
  'effect',
  'onCleanup',
  'onMount',
  'navigate',
  'useRoute',
  'props',
  'emit',
  'get',
  'post',
  'put',
  'patch',
  'del',
])

const RESERVED = new Set(
  (
    'break case catch class const continue debugger default delete do else enum export extends false finally for ' +
    'function if import in instanceof new null return super switch this throw true try typeof var void while with ' +
    'yield let static await implements interface package private protected public undefined NaN Infinity arguments eval'
  ).split(' '),
)

const SCRIPT_FILE = /\.(?:ts|js|mts|mjs)$/
const NOT_STATE = /\.(?:d|test|spec)\.(?:ts|js|mts|mjs)$/

const normalize = (path: string) => path.replaceAll('\\', '/')

/** What a state file exports, and of what kind: a signal (made by `state` or `derived`), a function or a value. */
export function readStateFile(source: string): StateMembers {
  const members: Record<string, StateMemberKind> = {}
  for (const binding of analyzeScript(source).bindings.values()) {
    if (!binding.exported) continue
    members[binding.name] =
      binding.signal === 'signal' ? 'signal' : binding.signal === 'callable' ? 'function' : 'value'
  }
  return members
}

/**
 * The shared state in a folder, from the paths of its files and a way to read one. A file that is not a script, or is
 * a declaration or a test, is not state. A file whose name a script cannot use, or that an api already has, gets a
 * diagnostic and is left out.
 */
export function buildStateList(
  files: string[],
  read: (file: string) => string,
  options: { apis?: readonly string[]; display?: (file: string) => string } = {},
): { states: ProjectState[]; diagnostics: StateDiagnostic[] } {
  const display = options.display ?? ((f: string) => f)
  const states: ProjectState[] = []
  const diagnostics: StateDiagnostic[] = []
  const sorted = [...files].map(normalize).sort((a, b) => a.localeCompare(b))
  for (const file of sorted) {
    const base = file.split('/').pop()!
    if (!SCRIPT_FILE.test(base) || NOT_STATE.test(base)) continue
    const name = base.replace(SCRIPT_FILE, '')
    const fail = (message: string, hint?: string) =>
      diagnostics.push({
        code: 'T5010',
        severity: 'error',
        file: display(file),
        line: 1,
        column: 1,
        message,
        ...(hint ? { hint } : {}),
      })
    if (!/^[A-Za-z_$][\w$]*$/.test(name) || RESERVED.has(name)) {
      fail(
        `"${name}" cannot be the name of shared state: it is not a name a script can use.`,
        'Rename the file to letters, numbers and underscores, starting with a letter, such as cart.ts.',
      )
      continue
    }
    if (TAKEN.has(name)) {
      fail(
        `"${name}" cannot be the name of shared state: Tessera already uses it.`,
        'Rename the file, for example cart.ts.',
      )
      continue
    }
    if (options.apis?.includes(name)) {
      fail(`"${name}" is the name of an API and of shared state. Rename one of the files.`)
      continue
    }
    states.push({ name, file, members: readStateFile(read(file)) })
  }
  return { states, diagnostics }
}

/**
 * `.tessera/state.d.ts`: each piece of shared state as a name TypeScript knows in a `.tess` script, typed as what its
 * file exports. `dir` is the folder the file is written in, for the paths.
 */
export function generateStateDts(states: readonly ProjectState[], dir: string): string {
  const lines = ['// Generated by Tessera. Do not edit.', '']
  const from = normalize(dir).split('/')
  for (const state of states) {
    const to = normalize(state.file).replace(SCRIPT_FILE, '').split('/')
    let same = 0
    while (same < from.length && same < to.length && from[same] === to[same]) same++
    const path = [...from.slice(same).map(() => '..'), ...to.slice(same)].join('/')
    lines.push(`declare const ${state.name}: typeof import('${path}')`)
  }
  lines.push('')
  return lines.join('\n')
}

/** `a`, `a or b`, `a, b or c`. */
export const orWords = (items: string[]): string =>
  items.length < 2 ? (items[0] ?? '') : `${items.slice(0, -1).join(', ')} or ${items.at(-1)}`

/** The file of a piece of state as a script is told about it: `app/state/cart.ts`. */
export const stateFileLabel = (file: string): string =>
  `app/state/${normalize(file).split('/').pop()}`

/**
 * What to say after "can only be changed inside app/state/cart.ts": the functions the file has, or that it needs one.
 * \`name\` is the state, \`members\` its exports.
 */
export function changeHint(name: string, members: StateMembers): string {
  const functions = Object.entries(members)
    .filter(([, kind]) => kind === 'function')
    .map(([key]) => `${name}.${key}()`)
  return functions.length
    ? `Change it with ${orWords(functions)}, or add a function to that file.`
    : 'Add a function to that file that changes it, and call that.'
}
