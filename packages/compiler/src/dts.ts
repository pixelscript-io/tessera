import { generateTypes } from '@tessera/contract'
import type { ComponentRegistry } from './registry'

/**
 * `.tessera/components.d.ts`: types for every registered component, so an editor knows each component
 * tag, its variant props, slots and events, and so TypeScript code that imports a `.tess` file (an app's
 * `main.ts`, a test) gets those types for the component it imports.
 *
 * The file is a script, not a module, because wildcard module declarations are only allowed there. The
 * per-component types live in the `TesseraComponents` namespace, and each `declare module '*\/Name.tess'`
 * types the default export of a file by its name.
 */
export function generateComponentsDts(registry: ComponentRegistry): string {
  const entries = [...registry.entries.values()]
  const lines = [
    '// Generated by Tessera. Do not edit.',
    '',
    'declare namespace TesseraComponents {',
    '  /** A compiled component: call it with props (as signals), event handlers and slot content. */',
    '  type Component<P, E, S> = (input?: {',
    "    props?: { [K in keyof P]?: import('@pixelscriptio/tessera/core').ReadonlySignal<P[K]> } & Record<string, import('@pixelscriptio/tessera/core').ReadonlySignal<any>>",
    '    events?: { [K in keyof E]?: (detail?: any) => void }',
    "    slots?: { [K in keyof S]?: import('@pixelscriptio/tessera/core').SlotContent }",
    '  }) => any',
    '',
  ]

  for (const { contract } of entries) {
    // generateTypes writes top-level `export interface` declarations; inside a namespace they are exported members.
    const body = generateTypes(contract)
      .split('\n')
      .slice(2)
      .map((l) => (l ? `  ${l}` : l))
    lines.push(`  // ${contract.name}`, ...body)
  }

  lines.push(
    '  /** Every component tag, with its props, events and slots. */',
    '  interface Tags {',
  )
  for (const { contract } of entries) {
    const n = contract.name
    lines.push(
      `    ${n}: { props: ${n}Props; events: ${n}Events; slots: ${n}Slots; parts: ${n}Part }`,
    )
  }
  lines.push('  }', '}', '')

  for (const { contract } of entries) {
    const n = contract.name
    lines.push(
      `declare module '*/${n}.tess' {`,
      `  const component: TesseraComponents.Component<TesseraComponents.${n}Props, TesseraComponents.${n}Events, TesseraComponents.${n}Slots>`,
      '  export default component',
      '}',
      '',
    )
  }
  return lines.join('\n')
}
