import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { loadProjectState } from '../src/node'
import { Project } from '../src/project'
import { generateStateDts } from '../src/shared-state'

const CART = `import { state, derived } from '@pixelscriptio/tessera/core'
export const items = state([])
export const count = derived(() => items.value.length)
export function add(item) { items.value = [...items.value, item] }
`

function project(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'tessera-state-'))
  for (const [file, text] of Object.entries(files)) {
    const path = join(root, file)
    mkdirSync(join(path, '..'), { recursive: true })
    writeFileSync(path, text)
  }
  return root
}

describe('the shared state of a project on disk', () => {
  it('is each script file in app/state, with what it exports', () => {
    const root = project({
      'app/state/cart.ts': CART,
      'app/state/notes.md': '# not state',
      'app/state/cart.test.ts': 'test',
    })
    const loaded = loadProjectState(root)
    expect(loaded.diagnostics).toEqual([])
    expect(loaded.states.map((s) => [s.name, s.members])).toEqual([
      ['cart', { items: 'signal', count: 'signal', add: 'function' }],
    ])
  })

  it('has no state, and no error, when there is no folder', () => {
    const loaded = loadProjectState(project({ 'app/pages/index.tess': '' }))
    expect(loaded.states).toEqual([])
    expect(loaded.diagnostics).toEqual([])
  })

  it('refuses a file with the name of an api, and shows its path', () => {
    const root = project({ 'app/state/github.ts': CART, 'app/apis/github.ts': 'export default 1' })
    const project1 = new Project(root, { contracts: 'optional' })
    expect(project1.state().states).toEqual([])
    expect(project1.state().diagnostics.map((d) => `${d.code} ${d.file}`)).toEqual([
      'T5010 app/state/github.ts',
    ])
  })
})

describe('compiling with the shared state of a project', () => {
  const PAGE =
    '<template><main><p>{cart.count}</p><button @click="cart.add(1)">Add</button></main></template>\n'

  it('imports the state and reads its signals', () => {
    const root = project({ 'app/state/cart.ts': CART, 'app/pages/index.tess': PAGE })
    const found = new Project(root, { contracts: 'optional' })
    const checked = found.compileFile(join(root, 'app/pages/index.tess'), PAGE, { baseline: null })
    expect(checked.diagnostics.map((d) => `${d.code} ${d.message}`)).toEqual([])
    expect(checked.result.code).toContain('import * as cart from "../state/cart.ts"')
    expect(checked.result.code).toContain('cart.count.value')
  })

  it('sees a member added to the file after the project was read, once it is reset', () => {
    const root = project({ 'app/state/cart.ts': CART })
    const found = new Project(root, { contracts: 'optional' })
    const page = '<template><main>{cart.total}</main></template>\n'
    const before = found.compileFile(join(root, 'app/pages/p.tess'), page, { baseline: null })
    expect(before.diagnostics.map((d) => d.code)).toEqual(['T5012'])
    writeFileSync(join(root, 'app/state/cart.ts'), CART + 'export const total = derived(() => 1)\n')
    found.resetState()
    const after = found.compileFile(join(root, 'app/pages/p.tess'), page, { baseline: null })
    expect(after.diagnostics).toEqual([])
  })
})

describe('.tessera/state.d.ts', () => {
  it('declares each piece of state as the module of its file', () => {
    const text = generateStateDts(
      [{ name: 'cart', file: '/p/app/state/cart.ts', members: {} }],
      '/p/.tessera',
    )
    expect(text).toBe(
      "// Generated by Tessera. Do not edit.\n\ndeclare const cart: typeof import('../app/state/cart')\n",
    )
  })
})
