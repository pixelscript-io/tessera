import type { PropInfo } from '@tessera/compiler'

/**
 * What a component is, as the files that let other frameworks use it need it: its tag, its variants, props, events and
 * slots. Built from the contract and the script's props by the `elements` command; the generators below are pure.
 */
export interface ElementInfo {
  /** The contract name, `AccordionItem`. */
  name: string
  /** The tag it is registered as, `t-accordion-item`. */
  tag: string
  description?: string
  variants: Array<{ name: string; values: string[]; default: string }>
  props: PropInfo[]
  events: Record<string, string>
  slots: Record<string, string>
}

/** `AccordionItem` to `accordion-item`. */
export const kebab = (name: string): string =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()

/** `press` to `onPress`, `toggle-all` to `onToggleAll`. */
export const handlerName = (event: string): string =>
  'on' +
  event
    .split(/[-:]/)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('')

/** The tag a component is registered as: the prefix, a hyphen, and its name in kebab case. */
export const tagName = (prefix: string, name: string): string => `${prefix}-${kebab(name)}`

/** The TypeScript type of a prop. */
function typeOf(prop: PropInfo): string {
  switch (prop.type) {
    case 'boolean':
      return 'boolean'
    case 'number':
      return 'number'
    case 'string':
      return 'string'
    case 'array':
      return 'Array<any>'
    case 'object':
      return 'Record<string, any>'
    default:
      return 'any'
  }
}

const union = (values: string[]) => values.map((v) => JSON.stringify(v)).join(' | ')
const className = (name: string) => `${name}Element`

const comment = (text: string | undefined, indent = '  ') =>
  text ? `${indent}/** ${text.replaceAll('*/', '*\\/')} */\n` : ''

/** The element classes and the tag map, for TypeScript code that uses the elements directly. */
export function elementsDts(infos: ElementInfo[]): string {
  const out: string[] = ['// Generated by `tessera elements`. Do not edit.', '']
  for (const c of infos) {
    const events = Object.keys(c.events)
    out.push(
      `${comment(c.description, '')}export interface ${className(c.name)} extends HTMLElement {`,
    )
    for (const v of c.variants)
      out.push(
        `${comment(`One of ${v.values.join(', ')}. Default ${v.default}.`)}  ${v.name}: ${union(v.values)}`,
      )
    for (const p of c.props)
      out.push(
        `  ${/^[A-Za-z_$][\w$]*$/.test(p.name) ? p.name : JSON.stringify(p.name)}: ${typeOf(p)}`,
      )
    for (const event of events) {
      out.push(
        `${comment(c.events[event])}  addEventListener(type: ${JSON.stringify(event)}, listener: (this: ${className(c.name)}, event: CustomEvent<any>) => any, options?: boolean | AddEventListenerOptions): void`,
      )
    }
    out.push(
      '  addEventListener<K extends keyof HTMLElementEventMap>(type: K, listener: (this: ' +
        className(c.name) +
        ', ev: HTMLElementEventMap[K]) => any, options?: boolean | AddEventListenerOptions): void',
    )
    out.push(
      '  addEventListener(type: string, listener: EventListenerOrEventListenerObject, options?: boolean | AddEventListenerOptions): void',
    )
    out.push('}', '')
  }
  out.push('declare global {', '  interface HTMLElementTagNameMap {')
  for (const c of infos) out.push(`    ${JSON.stringify(c.tag)}: ${className(c.name)}`)
  out.push('  }', '}', '', 'export {}', '')
  return out.join('\n')
}

/** The names a React wrapper treats as properties of the element rather than attributes: variants and props. */
function propNames(c: ElementInfo): string[] {
  return [...c.variants.map((v) => v.name), ...c.props.map((p) => p.name)]
}

/**
 * React components that wrap the elements. They set variants and props as properties (so a list or a boolean arrives
 * as what it is, in any version of React), pass the rest to the element as attributes (\`aria-*\`, \`class\`, \`slot\`),
 * and turn each event into an \`on<Event>\` prop. They have no JSX, so they need no build step, and React is the
 * project's own.
 */
export function reactModule(infos: ElementInfo[]): string {
  const specs = infos.map((c) => ({
    export: c.name,
    tag: c.tag,
    props: propNames(c),
    events: Object.fromEntries(Object.keys(c.events).map((e) => [handlerName(e), e])),
  }))
  return `// Generated by \`tessera elements\`. Do not edit.
import { createElement, forwardRef, useEffect, useImperativeHandle, useLayoutEffect, useRef } from 'react'
import './elements.js'

function wrap(name, tag, props, events) {
  const component = forwardRef(function TesseraElement(given, ref) {
    const element = useRef(null)
    useImperativeHandle(ref, () => element.current)
    const { children, className, ...rest } = given
    const values = {}
    const listeners = {}
    const attributes = {}
    for (const [key, value] of Object.entries(rest)) {
      if (key in events) listeners[events[key]] = value
      else if (props.includes(key)) values[key] = value
      else attributes[key] = value
    }
    if (className) attributes.class = className
    // Properties on the element, after it is in the page: a list or a boolean is passed as itself.
    useLayoutEffect(() => {
      for (const [key, value] of Object.entries(values)) if (element.current) element.current[key] = value
    })
    useEffect(() => {
      const target = element.current
      if (!target) return undefined
      const added = Object.entries(listeners).filter(([, f]) => typeof f === 'function')
      for (const [event, handler] of added) target.addEventListener(event, handler)
      return () => {
        for (const [event, handler] of added) target.removeEventListener(event, handler)
      }
    })
    return createElement(tag, { ref: element, ...attributes }, children)
  })
  component.displayName = name
  return component
}

${specs.map((s) => `export const ${s.export} = wrap(${JSON.stringify(s.export)}, ${JSON.stringify(s.tag)}, ${JSON.stringify(s.props)}, ${JSON.stringify(s.events)})`).join('\n')}
`
}

/** Types for the React wrappers: each component's props, with the events as \`on<Event>\`. */
export function reactDts(infos: ElementInfo[]): string {
  const out: string[] = [
    '// Generated by `tessera elements`. Do not edit.',
    "import type { ForwardRefExoticComponent, HTMLAttributes, ReactNode, RefAttributes } from 'react'",
    "import type * as Elements from './elements.js'",
    '',
  ]
  for (const c of infos) {
    const handlers = Object.keys(c.events).map(handlerName)
    // React's own on* props for the same events (onInput, onChange, onToggle) are not what the component emits.
    const omit = [...new Set(['onSelect', 'onInput', 'onChange', 'onToggle', ...handlers])]
    out.push(
      `${comment(c.description, '')}export interface ${c.name}Props extends Omit<HTMLAttributes<HTMLElement>, ${omit.map((o) => `'${o}'`).join(' | ')}> {`,
    )
    for (const v of c.variants)
      out.push(
        `${comment(`One of ${v.values.join(', ')}. Default ${v.default}.`)}  ${v.name}?: ${union(v.values)}`,
      )
    for (const p of c.props)
      out.push(
        `  ${/^[A-Za-z_$][\w$]*$/.test(p.name) ? p.name : JSON.stringify(p.name)}?: ${typeOf(p)}`,
      )
    for (const [event, description] of Object.entries(c.events))
      out.push(`${comment(description)}  ${handlerName(event)}?: (event: CustomEvent<any>) => void`)
    out.push('  children?: ReactNode', '}')
    out.push(
      `${comment(c.description, '')}export const ${c.name}: ForwardRefExoticComponent<${c.name}Props & RefAttributes<Elements.${className(c.name)}>>`,
      '',
    )
  }
  return out.join('\n')
}

/** How to use the folder, written for someone who has never seen Tessera. */
export function elementsReadme(
  infos: ElementInfo[],
  options: { prefix: string; project: string },
): string {
  const first = infos.find((c) => c.name === 'Button') ?? infos[0]!
  const withSlot = infos.find((c) => 'default' in c.slots) ?? first
  return `# ${options.project}: components as custom elements

Generated by \`tessera elements\`. Do not edit.

The components of the design system as standard custom elements, for any framework or none. They carry their own
styles and the design tokens, so there is nothing else to install.

## Use

\`\`\`html
<link rel="stylesheet" href="elements.css" />
<script type="module" src="elements.js"></script>

<${withSlot.tag}>${withSlot.name}</${withSlot.tag}>
\`\`\`

Variants and props are attributes and properties, events are DOM events with the payload in \`detail\`, and slots are
children (\`<span slot="title">…</span>\`):

\`\`\`js
const el = document.querySelector('${first.tag}')
el.addEventListener(${JSON.stringify(Object.keys(first.events)[0] ?? 'press')}, (event) => console.log(event.detail))
\`\`\`

A boolean is on when its attribute is present. A list is set as a property (\`el.options = [...]\`) or as JSON in the
attribute. Slot content is read when the element is added to the page.

## Themes

The tokens and their themes are in \`elements.css\`. Switch themes the same way as in a Tessera app, with an attribute on
the page: \`document.documentElement.setAttribute('data-theme', 'dark')\`.

## React

\`\`\`jsx
import { ${first.name} } from './react.js'
import './elements.css'

<${first.name}${first.variants[0] ? ` ${first.variants[0].name}="${first.variants[0].values[first.variants[0].values.length - 1]}"` : ''}${Object.keys(first.events)[0] ? ` ${handlerName(Object.keys(first.events)[0]!)}={(event) => console.log(event.detail)}` : ''}>…</${first.name}>
\`\`\`

\`react.js\` has no JSX and needs no build step; \`react\` is your own. \`react.d.ts\` has the props.

## Vue, Svelte, Angular and others

Custom elements work in them directly. In Vue, tell the compiler the tags are not Vue components:
\`app.config.compilerOptions.isCustomElement = (tag) => tag.startsWith('${options.prefix}-')\`.

## What is here

${infos.map((c) => `- \`<${c.tag}>\`${c.description ? `: ${c.description}` : ''}`).join('\n')}

Files: \`elements.js\`, \`elements.css\`, \`elements.d.ts\` (types), \`react.js\` and \`react.d.ts\`, \`custom-elements.json\`
(the manifest editors and docs tools read).
`
}
