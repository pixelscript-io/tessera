import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { tessera } from '@tessera/compiler/vite'
import { build } from 'vite'
import type { Registry } from '../registry/build'
import { liveExamples } from './build'

export interface LiveOptions {
  /**
   * Where the throwaway project is made. It must be somewhere the framework resolves from (inside the repository), since
   * the components import `@pixelscriptio/tessera/core`.
   */
  workDir: string
  /** Where the bundle is written: `site.js`, `site.css` and `chunks/`. */
  outDir: string
  /** The token files the previews are styled with. */
  tokensDir: string
}

/** The script of the pages: it runs each `data-live` example, and adds a copy button to each block of code. */
function entry(keys: string[]): string {
  const examples = keys
    .map(
      (key) => `  ${JSON.stringify(key)}: () => import(${JSON.stringify(`./pages/${key}.tess`)}),`,
    )
    .join('\n')
  return `// Generated by tessera ui-site. Do not edit.
import 'virtual:tessera/tokens.css'
import { createRoot } from '@pixelscriptio/tessera/core'

const examples = {
${examples}
}

function show(slot, message) {
  const note = document.createElement('p')
  note.className = 'nojs'
  note.textContent = message
  slot.replaceChildren(note)
}

for (const slot of document.querySelectorAll('[data-live]')) {
  const load = examples[slot.dataset.live]
  if (!load) continue
  load()
    .then((mod) => createRoot(() => slot.replaceChildren(mod.default())))
    .catch((error) => show(slot, 'This preview could not run: ' + (error && error.message ? error.message : error)))
}

for (const block of document.querySelectorAll('figure.code')) {
  const pre = block.querySelector('pre')
  if (!pre) continue
  const button = document.createElement('button')
  button.type = 'button'
  button.className = 'copy'
  button.textContent = 'Copy'
  button.addEventListener('click', () => {
    navigator.clipboard.writeText(pre.textContent || '').then(
      () => {
        button.textContent = 'Copied'
        setTimeout(() => (button.textContent = 'Copy'), 1500)
      },
      () => (button.textContent = 'Press Ctrl+C'),
    )
  })
  block.append(button)
}

// The menu is open for a reader with no script. On a phone it starts folded away.
const menu = document.querySelector('details.menu')
if (menu && window.matchMedia('(max-width: 860px)').matches) menu.removeAttribute('open')
`
}

/**
 * Build the script and style sheet that make the previews of the site run. The examples of each component's docs page
 * and the components themselves are put in a small Tessera project and built with the same Vite plugin as an app, so a
 * preview is the real component, with its real behavior, not a picture of it.
 */
export async function buildLive(
  registry: Registry,
  options: LiveOptions,
): Promise<{ files: string[] }> {
  const root = resolve(options.workDir)
  const out = resolve(options.outDir)
  rmSync(root, { recursive: true, force: true })
  const write = (file: string, content: string) => {
    mkdirSync(dirname(join(root, file)), { recursive: true })
    writeFileSync(join(root, file), content)
  }
  write(
    'package.json',
    JSON.stringify({ name: 'tessera-ui-site', private: true, type: 'module' }) + '\n',
  )
  for (const item of registry.items)
    if (item.type === 'component')
      for (const file of item.files)
        if (!file.path.endsWith('.docs.md')) write(`system/components/${file.path}`, file.content)
  cpSync(options.tokensDir, join(root, 'system', 'tokens'), { recursive: true })
  const examples = liveExamples(registry)
  for (const example of examples) write(`pages/${example.key}.tess`, example.source)
  write('site.ts', entry(examples.map((e) => e.key)))

  rmSync(out, { recursive: true, force: true })
  await build({
    root,
    configFile: false,
    logLevel: 'warn',
    plugins: [tessera()],
    build: {
      outDir: out,
      emptyOutDir: true,
      minify: true,
      lib: {
        entry: join(root, 'site.ts'),
        formats: ['es'],
        fileName: () => 'site.js',
        cssFileName: 'site',
      },
      // Plain `.js` and a folder for the chunks, whose names carry a hash of their content so they can be cached for good.
      rollupOptions: {
        output: { entryFileNames: 'site.js', chunkFileNames: 'chunks/[name]-[hash].js' },
      },
    },
  })
  return { files: ['site.js', 'site.css'] }
}
