import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

/** A page's route, as the router knows it. */
export interface PrerenderRoute {
  path: string
  /** The page file, relative to `app/pages`. */
  file: string
  /** Names of the `[param]` segments. A route with any is not rendered: there is no value to give it. */
  params: string[]
}

export interface PrerenderResult {
  /** Files written, relative to the build folder. */
  written: string[]
  /** Routes that were not rendered, with why. */
  skipped: Array<{ path: string; reason: string }>
}

const forward = (path: string) => path.replaceAll('\\', '/')

/** The module the server loads: it renders any path of the app into HTML text, with no browser. */
const ENTRY = `// Generated by \`tessera build --prerender\`. Do not edit.
import { routes, notFound, layouts } from 'virtual:tessera/routes'
import { createRouter } from '@pixelscriptio/tessera/router'
import {
  clearAllApis,
  createStringAdapter,
  createStringNode,
  dataScript,
  exportPrefetched,
  failedPrefetches,
  serializeChildren,
  setRenderer,
} from '@pixelscriptio/tessera/core'

// Components render into a tree of text here instead of the page. Each element says the order it was made in, which is
// how the browser finds it again to hydrate the page.
const adapter = createStringAdapter({ marks: true })
setRenderer(adapter)

// The layouts a render loads, so the page can be given the styles of the layout it uses.
const used = new Set<string>()
const tracked = Object.fromEntries(
  Object.entries(layouts).map(([name, load]) => [
    name,
    () => {
      used.add(name)
      return (load as () => Promise<unknown>)()
    },
  ]),
) as typeof layouts

export async function render(
  path: string,
): Promise<{ html: string; title: string; layouts: string[]; data: string }> {
  used.clear()
  // Each page starts from the beginning: the numbering of its elements, and no answers left from the one before.
  adapter.reset()
  clearAllApis()
  const url = new URL(path, 'http://prerender.invalid')
  const doc = {
    title: '',
    getElementById: () => null,
    body: { append() {} },
    createElement: () => ({ setAttribute() {}, style: {}, remove() {} }),
  }
  const win = {
    location: { href: url.href, origin: url.origin },
    history: { scrollRestoration: 'auto', replaceState() {}, pushState() {} },
    document: doc,
    scrollX: 0,
    scrollY: 0,
    scrollTo() {},
    addEventListener() {},
    removeEventListener() {},
    dispatchEvent() {},
    setTimeout: (fn: () => void, ms: number) => setTimeout(fn, ms),
  }
  // The data a page declares is fetched before it is rendered, so the page is written with it.
  const router = createRouter({
    routes,
    notFound,
    layouts: tracked,
    window: win as unknown as Window,
    announce: false,
    waitForData: true,
  })
  const container = createStringNode('div')
  const stop = await router.mount(container as never)
  // A page whose declared data could not be had is not written: HTML that shows an error, hydrated with data that is
  // not there, would be wrong, and the page still works as an app.
  const failed = failedPrefetches()
  if (failed.length) {
    stop()
    throw new Error(
      'the data it declares could not be fetched at build time: ' +
        failed.map((f) => f.url + ' (' + f.message + ')').join('; '),
    )
  }
  const html = serializeChildren(container)
  const data = dataScript(exportPrefetched())
  stop()
  clearAllApis()
  return { html, title: doc.title, layouts: [...used], data }
}
`

const escapeHtml = (text: string) =>
  text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')

/** One entry of Vite's build manifest. */
interface ManifestChunk {
  css?: string[]
  imports?: string[]
}

/** The stylesheets a chunk needs: its own and those of everything it imports. Vite loads these with the script. */
function stylesheets(manifest: Record<string, ManifestChunk>, key: string | undefined): string[] {
  const out = new Set<string>()
  const seen = new Set<string>()
  const visit = (name: string) => {
    if (seen.has(name)) return
    seen.add(name)
    const chunk = manifest[name]
    if (!chunk) return
    for (const href of chunk.css ?? []) out.add(href)
    for (const next of chunk.imports ?? []) visit(next)
  }
  if (key) visit(key)
  return [...out]
}

/** A path nothing matches, so the router shows the not-found page. */
const NOT_FOUND_PATH = '/__tessera-not-found__'

/**
 * Render every page that has no parameters to HTML, after the build: each route becomes `<route>/index.html` and the
 * not-found page `404.html`, from the build's own `index.html` with the page in `#app` and its title in `<title>`.
 *
 * The page shows at once, with its content and styles, with or without JavaScript, and its data if it declared any
 * (`data` in its `<page>` block: fetched here, written into the page). When the script loads the page is hydrated:
 * the elements that are there are kept, so what the person did while it loaded is not lost. A page that cannot be
 * rendered outside a browser (its script reads \`window\`), or whose declared data could not be fetched, is skipped with
 * the reason, and still works as before.
 */
export async function prerender(
  root: string,
  outDir: string,
  routes: PrerenderRoute[],
): Promise<PrerenderResult> {
  const templatePath = join(outDir, 'index.html')
  if (!existsSync(templatePath)) {
    throw new Error(`There is no ${forward(templatePath)}: build the app first.`)
  }
  const template = readFileSync(templatePath, 'utf8')
  if (!/<div id="app"><\/div>/.test(template)) {
    throw new Error(
      'The page has no empty <div id="app"></div> to render into. Prerendering needs one in index.html.',
    )
  }

  // Styles that belong to a page or a layout are loaded by their script, so without JavaScript they would be missing:
  // each is linked in the HTML, from the build's manifest.
  const manifestPath = join(outDir, '.vite', 'manifest.json')
  const manifest: Record<string, ManifestChunk> = existsSync(manifestPath)
    ? (JSON.parse(readFileSync(manifestPath, 'utf8')) as Record<string, ManifestChunk>)
    : {}

  const dir = join(root, '.tessera', 'prerender')
  mkdirSync(dir, { recursive: true })
  const entry = join(dir, 'entry.ts')
  writeFileSync(entry, ENTRY)

  // Loaded here, not at the top: every command that is not a build starts without Vite.
  const { createServer } = await import('vite')
  const { tessera } = await import('@tessera/compiler/vite')
  const server = await createServer({
    root,
    configFile: false,
    logLevel: 'silent',
    appType: 'custom',
    plugins: [tessera()],
    server: { middlewareMode: true, hmr: false, watch: null },
    optimizeDeps: { noDiscovery: true, include: [] },
  })
  const result: PrerenderResult = { written: [], skipped: [] }
  try {
    const mod = (await server.ssrLoadModule(forward(entry))) as {
      render(
        path: string,
      ): Promise<{ html: string; title: string; layouts: string[]; data: string }>
    }
    const write = (
      file: string,
      page: { html: string; title: string; layouts: string[]; data: string },
      pageFile?: string,
    ) => {
      // The answers of the data the page declared go after the page, as JSON the browser does not run.
      let html = template.replace(
        '<div id="app"></div>',
        () => `<div id="app" data-prerendered>${page.html}</div>${page.data}`,
      )
      const links = [
        ...stylesheets(manifest, pageFile ? `app/pages/${pageFile}` : undefined),
        ...page.layouts.flatMap((name) => stylesheets(manifest, `app/layouts/${name}.tess`)),
      ]
        .filter((href, i, all) => all.indexOf(href) === i && !template.includes(`/${href}"`))
        .map((href) => `<link rel="stylesheet" crossorigin href="/${href}">`)
      if (links.length) html = html.replace('</head>', () => `${links.join('')}</head>`)
      if (page.title) {
        html = /<title>[\s\S]*?<\/title>/.test(html)
          ? html.replace(
              /<title>[\s\S]*?<\/title>/,
              () => `<title>${escapeHtml(page.title)}</title>`,
            )
          : html.replace('</head>', () => `<title>${escapeHtml(page.title)}</title></head>`)
      }
      const path = join(outDir, file)
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, html)
      result.written.push(file)
    }
    const attempt = async (route: string, file: string, pageFile?: string) => {
      try {
        write(file, await mod.render(route), pageFile)
      } catch (error) {
        result.skipped.push({
          path: route === NOT_FOUND_PATH ? '404' : route,
          reason: error instanceof Error ? error.message.split('\n')[0]! : String(error),
        })
      }
    }
    for (const route of routes) {
      if (route.params.length) {
        result.skipped.push({
          path: route.path,
          reason: `it has parameters (${route.params.map((p) => `:${p}`).join(', ')}), so there is no one page to render`,
        })
        continue
      }
      await attempt(
        route.path,
        route.path === '/' ? 'index.html' : `${route.path.replace(/^\//, '')}/index.html`,
        route.file,
      )
    }
    await attempt(NOT_FOUND_PATH, '404.html')
  } finally {
    await server.close()
  }
  return result
}
