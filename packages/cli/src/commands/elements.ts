import { mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { gzipSync } from 'node:zlib'
import { customElementsManifest } from '@tessera/agent'
import { componentProps } from '@tessera/compiler'
import type { Args } from '../args'
import { flag, has } from '../args'
import {
  elementsDts,
  elementsReadme,
  reactDts,
  reactModule,
  tagName,
  type ElementInfo,
} from '../elements'
import type { Io } from '../io'
import { CliError } from '../io'
import { openProject } from '../project'

const forward = (path: string) => path.replaceAll('\\', '/')

/** The tag prefix: lowercase letters and digits, starting with a letter, so `<prefix>-<name>` is a valid custom element. */
const PREFIX = /^[a-z][a-z0-9]*$/

/**
 * `tessera elements`: build the design system's components as custom elements, with React wrappers and types, so teams
 * that do not use Tessera can use the system. One self-contained folder: the elements and their runtime in one module,
 * the tokens and the components' styles in one stylesheet, and the files that describe them.
 */
export async function elements(args: Args, io: Io): Promise<number> {
  const project = await openProject(io.cwd, args)
  const given = flag(args, 'prefix')
  const prefix = typeof given === 'string' ? given : 't'
  if (!PREFIX.test(prefix)) {
    throw new CliError(
      `"${prefix}" cannot start a tag name.`,
      'Use lowercase letters and digits, starting with a letter: --prefix acme gives <acme-button>.',
    )
  }
  const outGiven = flag(args, 'out')
  const out = resolve(io.cwd, typeof outGiven === 'string' ? outGiven : 'dist-elements')

  const all = [...project.components().registry.entries.values()]
  const isSystem = (e: { file: string }) => forward(e.file).includes('/system/components/')
  const chosen = (has(args, 'all') ? all : all.filter(isSystem)).sort((a, b) =>
    a.name.localeCompare(b.name),
  )
  if (!chosen.length) {
    throw new CliError(
      'There are no design system components to build.',
      'Components in system/components are built by default. Pass --all to build the ones in app/components too.',
    )
  }

  const infos: ElementInfo[] = chosen.map((entry) => {
    const c = entry.contract!
    return {
      name: c.name,
      tag: tagName(prefix, c.name),
      ...(c.description ? { description: c.description } : {}),
      variants: Object.entries(c.variants).map(([name, values]) => ({
        name,
        values,
        default: values[0]!,
      })),
      props: componentProps(readFileSync(entry.file, 'utf8')),
      events: c.events,
      slots: c.slots,
    }
  })
  const tags = new Set<string>()
  for (const info of infos) {
    if (tags.has(info.tag)) throw new CliError(`Two components would both be <${info.tag}>.`)
    tags.add(info.tag)
  }

  // The entry the bundler starts from: each component, registered under its tag with what the element needs to know.
  const hasTokens = !!project.tokensDir()
  const entryDir = join(project.root, '.tessera', 'elements')
  mkdirSync(entryDir, { recursive: true })
  const entry = join(entryDir, 'entry.ts')
  const importName = (name: string) => `C_${name}`
  writeFileSync(
    entry,
    [
      '// Generated by `tessera elements`. Do not edit.',
      ...(hasTokens ? ["import 'virtual:tessera/tokens.css'"] : []),
      "import { defineElement } from '@pixelscriptio/tessera/core'",
      ...chosen.map((e) => `import ${importName(e.name)} from ${JSON.stringify(forward(e.file))}`),
      '',
      ...infos.map(
        (c) =>
          `defineElement(${JSON.stringify(c.tag)}, ${importName(c.name)}, ${JSON.stringify({
            variants: c.variants,
            props: c.props,
            events: Object.keys(c.events),
            slots: Object.keys(c.slots),
          })})`,
      ),
      '',
    ].join('\n'),
  )

  rmSync(out, { recursive: true, force: true })
  // Loaded here, not at the top: every other command starts without Vite.
  const { tessera } = await import('@tessera/compiler/vite')
  const { build } = await import('vite')
  await build({
    root: project.root,
    configFile: false,
    logLevel: 'warn',
    plugins: [tessera()],
    build: {
      outDir: out,
      emptyOutDir: true,
      target: 'es2022',
      cssCodeSplit: false,
      lib: {
        entry,
        formats: ['es'],
        fileName: () => 'elements.js',
        cssFileName: 'elements',
      },
    },
  })

  const projectName = (() => {
    try {
      return (
        (JSON.parse(readFileSync(join(project.root, 'package.json'), 'utf8')) as { name?: string })
          .name ?? 'Design system'
      )
    } catch {
      return 'Design system'
    }
  })()
  const manifest = project.agentManifest()
  const tagged = {
    ...manifest,
    components: manifest.components.filter((c) => infos.some((i) => i.name === c.name)),
  }
  const files: Record<string, string> = {
    'elements.d.ts': elementsDts(infos),
    'react.js': reactModule(infos),
    'react.d.ts': reactDts(infos),
    'custom-elements.json':
      JSON.stringify(
        customElementsManifest(tagged, {
          tagPrefix: prefix,
          props: Object.fromEntries(infos.map((i) => [i.name, i.props])),
          module: () => 'elements.js',
        }),
        null,
        2,
      ) + '\n',
    'README.md': elementsReadme(infos, { prefix, project: projectName }),
  }
  for (const [name, text] of Object.entries(files)) writeFileSync(join(out, name), text)

  const size = (name: string) => {
    const bytes = readFileSync(join(out, name))
    return { raw: statSync(join(out, name)).size, gzip: gzipSync(bytes).length }
  }
  const kb = (n: number) => `${(n / 1024).toFixed(1)} kB`
  const js = size('elements.js')
  const hasCss = (() => {
    try {
      statSync(join(out, 'elements.css'))
      return true
    } catch {
      return false
    }
  })()
  const css = hasCss ? size('elements.css') : undefined
  const where = (io.cwd === project.root ? out.slice(io.cwd.length + 1) : out) || out

  const ui = io.ui
  if (ui) {
    io.out(ui.ok(ui.bold(`Built ${infos.length} custom elements into ${forward(where)}`)))
    io.out('')
    io.out(ui.columns(infos.map((c) => [ui.accent(`<${c.tag}>`), ui.dim(c.description ?? '')])))
    io.out('')
    io.out(
      ui.columns([
        ['elements.js', ui.dim(`${kb(js.raw)}  (${kb(js.gzip)} gzipped)`)],
        ...(css ? [['elements.css', ui.dim(`${kb(css.raw)}  (${kb(css.gzip)} gzipped)`)]] : []),
        ['react.js', ui.dim('wrappers, no JSX')],
        ['*.d.ts', ui.dim('types for both')],
        ['custom-elements.json', ui.dim('for editors and docs tools')],
      ]),
    )
    io.out('')
    io.out(ui.dim('Open README.md in that folder for how to use it.'))
  } else {
    io.out(`Built ${infos.length} custom elements into ${forward(where)}.`)
    for (const c of infos) io.out(`  <${c.tag}>`)
    io.out(
      `elements.js ${kb(js.raw)} (${kb(js.gzip)} gzipped)${css ? `, elements.css ${kb(css.raw)} (${kb(css.gzip)} gzipped)` : ''}`,
    )
    io.out('Also: react.js, react.d.ts, elements.d.ts, custom-elements.json, README.md.')
  }
  return 0
}
