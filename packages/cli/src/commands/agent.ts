import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import {
  agentsMd,
  customElementsManifest,
  GENERATED_MARKER,
  llmsTxt,
  McpServer,
} from '@tessera/agent'
import type { Args } from '../args'
import { has } from '../args'
import { CliError, type Io } from '../io'
import { openProject } from '../project'
import type { Project } from '@tessera/compiler/project'
import { AGENT_GUIDE } from '../agent-guide'

const json = (value: unknown) => JSON.stringify(value, null, 2) + String.fromCharCode(10)

function writeIfChanged(path: string, text: string): boolean {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return false
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
  return true
}

/** `tessera manifest`: write `.tessera/manifest.json` and `.tessera/custom-elements.json`. */
export async function manifest(args: Args, io: Io): Promise<number> {
  const project = await openProject(io.cwd, args)
  const data = project.agentManifest()
  const dir = join(project.root, '.tessera')
  writeIfChanged(join(dir, 'manifest.json'), json(data))
  writeIfChanged(join(dir, 'custom-elements.json'), json(customElementsManifest(data)))
  io.out(
    `Wrote .tessera/manifest.json (${data.components.length} components, ${data.tokens.tokens.length} tokens, ${data.routes.routes.length} routes) and .tessera/custom-elements.json.`,
  )
  return 0
}

/**
 * The text of AGENTS.md and llms.txt for a project: the language guide, the rules, and what the project has (its
 * components, tokens, routes, APIs and state). `tessera init` writes them with this, and `tessera agent-files` again.
 */
export function agentFileContents(project: Project): {
  files: Array<[string, string]>
  manifest: string
} {
  const data = project.agentManifest()
  let name = 'This project'
  try {
    const pkg = JSON.parse(readFileSync(join(project.root, 'package.json'), 'utf8')) as {
      name?: string
    }
    if (pkg.name) name = pkg.name
  } catch {
    // No package.json: keep the generic name.
  }
  return {
    files: [
      ['AGENTS.md', agentsMd(data, { guide: AGENT_GUIDE })],
      ['llms.txt', llmsTxt(data, name)],
    ],
    manifest: json(data),
  }
}

/** `tessera agent-files`: write AGENTS.md and llms.txt, never over a file the person wrote. */
export async function agentFiles(args: Args, io: Io): Promise<number> {
  const project = await openProject(io.cwd, args)
  const force = has(args, 'force')
  const { files, manifest: manifestText } = agentFileContents(project)
  const kept: string[] = []
  for (const [file, text] of files) {
    const path = join(project.root, file)
    // llms.txt has no comment syntax, so it is recognised by its generated sentence instead.
    const ours = existsSync(path) && isGenerated(readFileSync(path, 'utf8'))
    if (existsSync(path) && !ours && !force) {
      kept.push(file)
      continue
    }
    io.out(`${writeIfChanged(path, text) ? 'Wrote' : 'Up to date:'} ${file}`)
  }
  writeIfChanged(join(project.root, '.tessera', 'manifest.json'), manifestText)
  if (kept.length) {
    io.out(
      `Left ${kept.join(' and ')} alone: ${kept.length === 1 ? 'it was' : 'they were'} not generated by Tessera. Use --force to replace ${kept.length === 1 ? 'it' : 'them'}.`,
    )
  }
  return 0
}

/**
 * Bring AGENTS.md and llms.txt up to date after the project changed (a component added), but only the ones Tessera wrote:
 * a file the person wrote is theirs, and a project with none has not asked for one. Returns the files it rewrote.
 */
export function refreshAgentFiles(project: Project): string[] {
  const { files, manifest } = agentFileContents(project)
  const updated: string[] = []
  for (const [file, text] of files) {
    const path = join(project.root, file)
    if (!existsSync(path) || !isGenerated(readFileSync(path, 'utf8'))) continue
    if (writeIfChanged(path, text)) updated.push(file)
  }
  const manifestPath = join(project.root, '.tessera', 'manifest.json')
  if (updated.length && existsSync(manifestPath)) writeIfChanged(manifestPath, manifest)
  return updated
}

const isGenerated = (text: string) =>
  text.startsWith(GENERATED_MARKER) ||
  text.includes('> A Tessera project: components with contracts')

/** `tessera mcp`: a read-only MCP server on stdin and stdout. */
export async function mcp(args: Args, io: Io): Promise<number> {
  if (!io.stdin || !io.stdout) throw new CliError('The MCP server needs standard input and output.')
  const project = await openProject(io.cwd, args)
  // stdout carries the protocol, so anything a person should read goes to stderr.
  io.err(
    `Tessera MCP server for ${project.display(project.root) || '.'} (read-only). Waiting for a client on standard input.`,
  )
  await new McpServer(project).serve(io.stdin, io.stdout)
  return 0
}
