import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadConfigFile, Project } from '@tessera/compiler/project'
import { searchForWorkspaceRoot, type HmrContext, type Plugin, type ViteDevServer } from 'vite'
import { API_PREFIX, authorize, Editor } from './api'
import { buildDocsData, type DocsData } from './data'

const DATA_ID = 'virtual:tessera-docs/data'
const COMPONENTS_ID = 'virtual:tessera-docs/components'
const RUNTIME_ID = 'virtual:tessera-docs/runtime'
const RESOLVED = (id: string) => '\0' + id
const VIRTUAL_IDS = [DATA_ID, COMPONENTS_ID, RUNTIME_ID]

/** The folder the docs app writes its generated files into, inside the project's own `.tessera`. */
export const DOCS_DIR = ['.tessera', 'docs']

/** The most the write interface reads from one request: a token export is the largest thing sent. */
const MAX_BODY = 8 * 1024 * 1024

export interface DocsOptions {
  /** `tessera report` as JSON; the host passes it in because the report lives with the CLI. */
  report?: (project: Project) => unknown
  /** Turn on the system manager (the write interface). Off, every write route answers 404. */
  edit?: boolean
  /** The per-run secret the write interface requires. Make one with `newSecret()`. */
  secret?: string
}

/** Where the client source is: next to this file when running from source, in `docs-client/` once packaged. */
export function clientEntry(): string {
  const here = dirname(fileURLToPath(import.meta.url))
  for (const candidate of [join(here, 'client', 'main.ts'), join(here, 'docs-client', 'main.ts')]) {
    if (existsSync(candidate)) return candidate.replaceAll('\\', '/')
  }
  throw new Error('The docs app files were not found next to the package.')
}

const forward = (p: string) => p.replaceAll('\\', '/')

/** The HTML page of the docs app. */
export function docsHtml(title: string, script: string, stylesheet?: string): string {
  const lines = [
    '<!doctype html>',
    '<html lang="en">',
    '  <head>',
    '    <meta charset="UTF-8" />',
    '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />',
    `    <title>${title.replaceAll('&', '&amp;').replaceAll('<', '&lt;')}</title>`,
    ...(stylesheet ? [`    <link rel="stylesheet" href="${stylesheet}" />`] : []),
    '  </head>',
    '  <body>',
    '    <div id="docs"></div>',
    `    <script type="module" src="${script}"></script>`,
    '  </body>',
    '</html>',
    '',
  ]
  return lines.join(String.fromCharCode(10))
}

function writeIfChanged(path: string, text: string): void {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
}

/**
 * The docs app as a Vite plugin: three virtual modules (the data, the components, the runtime) the client reads,
 * the generated entry and `tess live` example pages under `.tessera/docs`, and, in dev, a reload when a
 * component, a token or a `.docs.md` file changes, so a new component shows up without a restart.
 */
export function docsPlugin(options: DocsOptions = {}): Plugin {
  let root = process.cwd()
  let project: Project
  let data: DocsData | undefined
  let hasTokens = false
  let editor: Editor | undefined

  const docsDir = () => join(root, ...DOCS_DIR)
  const liveModule = (component: string, index: number) =>
    `/${DOCS_DIR.join('/')}/pages/${component}-${index}.tess`

  /** Rebuild the data, and write the files the client imports: the entry and a page for each live example. */
  const refresh = (): DocsData => {
    project.resetAll()
    data = buildDocsData(project, {
      report: options.report?.(project),
      liveModule,
    })
    hasTokens = data.hasTokens
    const pages = join(docsDir(), 'pages')
    const wanted = new Set<string>()
    for (const c of data.components) {
      c.prose?.live.forEach((block, i) => {
        const file = `${c.name}-${i}.tess`
        wanted.add(file)
        writeIfChanged(
          join(pages, file),
          block.source.endsWith('\n') ? block.source : block.source + '\n',
        )
      })
    }
    if (existsSync(pages)) {
      for (const f of readdirSync(pages))
        if (!wanted.has(f)) rmSync(join(pages, f), { force: true })
    }
    writeIfChanged(
      join(docsDir(), 'main.ts'),
      [
        '// Generated by Tessera. Do not edit.',
        ...(hasTokens ? ["import 'virtual:tessera/tokens.css'"] : []),
        `import '${clientEntry()}'`,
        '',
      ].join(String.fromCharCode(10)),
    )
    return data
  }

  const components = (): string => {
    const current = data ?? refresh()
    const entries = current.components.map((c) => {
      // A project with no design tokens cannot compile a component whose styles use them (the router's Link does),
      // and a static build compiles every component it names: say so in the preview instead.
      if (!current.hasTokens && c.tokenRefs > 0) {
        const why = `${c.name} styles itself with design tokens, and this project has none.`
        return `  ${JSON.stringify(c.name)}: () => Promise.reject(new Error(${JSON.stringify(why)})),`
      }
      const abs = forward(join(root, c.file))
      return `  ${JSON.stringify(c.name)}: () => import(${JSON.stringify(abs)}),`
    })
    // The live examples of the prose are generated pages; naming them here is what puts them in a static build.
    const live = current.components.flatMap((c) =>
      (c.prose?.live ?? []).map(
        (b) =>
          `  ${JSON.stringify(b.module)}: () => import(${JSON.stringify(forward(join(root, b.module)))}),`,
      ),
    )
    return `export const components = {\n${entries.join('\n')}\n}\nexport const live = {\n${live.join('\n')}\n}\n`
  }

  const invalidate = (server: ViteDevServer) => {
    for (const id of VIRTUAL_IDS) {
      const module = server.moduleGraph.getModuleById(RESOLVED(id))
      if (module) server.moduleGraph.invalidateModule(module)
    }
  }

  return {
    name: 'tessera:docs',
    enforce: 'pre',

    config(user) {
      const base = user.root ?? process.cwd()
      return {
        optimizeDeps: { exclude: ['@pixelscriptio/tessera'] },
        // The default (the project's workspace) plus the folder the docs app itself is served from.
        server: { fs: { allow: [searchForWorkspaceRoot(base), dirname(clientEntry())] } },
      }
    },

    async configResolved(config) {
      root = config.root
      const fromFile = await loadConfigFile(root)
      project = new Project(root, { ...fromFile?.options })
      editor = new Editor(project, { edit: !!options.edit, secret: options.secret ?? '' })
      refresh()
    },

    resolveId(id) {
      return VIRTUAL_IDS.includes(id) ? RESOLVED(id) : null
    },

    load(id) {
      if (id === RESOLVED(DATA_ID)) {
        return `export default ${JSON.stringify({ ...(data ?? refresh()), edit: !!options.edit })}`
      }
      if (id === RESOLVED(COMPONENTS_ID)) return components()
      if (id === RESOLVED(RUNTIME_ID)) {
        return "export { state, createRoot, getRenderer, previewComponents, previewSlots } from '@pixelscriptio/tessera/core'\n"
      }
      return null
    },

    configureServer(server) {
      const watch = [
        join(root, 'app', 'components'),
        join(root, 'system'),
        ...(project.tokensDir() ? [project.tokensDir()!] : []),
        ...project.components().dirs,
      ]
      server.watcher.add(watch)

      const relevant = (file: string) => {
        const f = forward(file)
        if (f.includes('/.tessera/') || f.includes('/node_modules/')) return false
        return f.endsWith('.tess') || f.endsWith('.docs.md') || f.endsWith('.tokens.json')
      }
      let timer: ReturnType<typeof setTimeout> | undefined
      const changed = (file: string) => {
        if (!relevant(file) || forward(file).includes('/app/pages/')) return
        clearTimeout(timer)
        timer = setTimeout(() => {
          refresh()
          invalidate(server)
          server.ws.send({ type: 'full-reload' })
        }, 80)
      }
      server.watcher.on('add', changed)
      server.watcher.on('unlink', changed)
      server.watcher.on('change', changed)

      // The write interface. It answers every request itself, including with a 404 when editing is off.
      server.middlewares.use((req, res, next) => {
        const url = req.url ?? '/'
        if (!url.startsWith(API_PREFIX) || !editor) return next()
        const headers: Record<string, string | undefined> = {}
        for (const [name, value] of Object.entries(req.headers)) {
          headers[name] = Array.isArray(value) ? value[0] : value
        }
        // Refuse before reading a byte of the body: a client with no key must not make the server buffer anything.
        const denied = authorize({ method: req.method ?? 'GET', url, headers }, editor.options)
        if (denied) {
          req.resume()
          res.statusCode = denied.status
          res.setHeader('Content-Type', 'application/json')
          res.setHeader('Cache-Control', 'no-store')
          res.setHeader('Connection', 'close')
          res.end(JSON.stringify(denied.body))
          return
        }
        const chunks: Buffer[] = []
        let size = 0
        let refused = false
        req.on('data', (chunk: Buffer) => {
          size += chunk.length
          if (size > MAX_BODY) refused = true
          else chunks.push(chunk)
        })
        req.on('end', () => {
          const out = refused
            ? { status: 413, body: { error: 'That is too large for the editor.' } }
            : editor!.handle({
                method: req.method ?? 'GET',
                url,
                headers,
                body: Buffer.concat(chunks).toString('utf8'),
              })
          res.statusCode = out.status
          res.setHeader('Content-Type', 'application/json')
          res.setHeader('Cache-Control', 'no-store')
          res.end(JSON.stringify(out.body))
        })
      })

      // Before Vite's own middleware: every page request gets the docs page.
      server.middlewares.use((req, res, next) => {
        const url = req.url ?? '/'
        const wantsPage =
          (req.method === 'GET' || req.method === 'HEAD') &&
          !/\.[a-z0-9]+(\?|$)/i.test(url) &&
          !url.startsWith('/@') &&
          !url.startsWith('/__')
        if (!wantsPage || !(req.headers.accept ?? '').includes('text/html')) return next()
        server
          .transformIndexHtml(
            url,
            docsHtml(`${(data ?? refresh()).project.name} docs`, `/${DOCS_DIR.join('/')}/main.ts`),
          )
          .then((html) => {
            res.setHeader('Content-Type', 'text/html')
            res.end(html)
          })
          .catch(next)
      })
    },

    handleHotUpdate(ctx: HmrContext) {
      // A docs file has no module of its own; the watcher above reloads the page.
      if (ctx.file.endsWith('.docs.md')) return []
      return undefined
    },
  }
}
