import type { AgentManifest } from '@tessera/compiler'

/**
 * The components as a `custom-elements.json` (schema 1.0.0), the format editors and component tooling already
 * read. Tessera components are not registered custom elements, so a declaration has no `tagName`: the name is
 * the tag you write in a template. Variants are attributes, events are events, parts are `cssParts`.
 */
export interface CustomElementsManifest {
  schemaVersion: '1.0.0'
  readme?: string
  modules: Array<{
    kind: 'javascript-module'
    path: string
    declarations: Array<{
      kind: 'class'
      name: string
      tagName?: string
      customElement?: boolean
      description?: string
      deprecated?: string | boolean
      attributes: Array<{
        name: string
        type: { text: string }
        default: string
        description: string
      }>
      events: Array<{ name: string; description: string }>
      slots: Array<{ name: string; description: string }>
      cssParts: Array<{ name: string; description: string }>
      cssStates: Array<{ name: string; description: string }>
    }>
    exports: Array<{ kind: 'js'; name: string; declaration: { name: string; module: string } }>
  }>
}

export interface CustomElementsOptions {
  /**
   * Register the components as custom elements with this tag prefix (`t` gives `<t-button>`): each declaration gets
   * its `tagName` and `customElement: true`. Without it the components are not custom elements, and have no tag.
   */
  tagPrefix?: string
  /** The props each component's script names, by component name, which are attributes too. */
  props?: Record<string, Array<{ name: string; type: string; default?: unknown }>>
  /** The module a component is exported from. Defaults to the component's own file. */
  module?: (file: string) => string
}

const kebab = (name: string) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()

export function customElementsManifest(
  manifest: AgentManifest,
  options: CustomElementsOptions = {},
): CustomElementsManifest {
  return {
    schemaVersion: '1.0.0',
    readme: 'Generated by `tessera manifest`. Do not edit.',
    modules: manifest.components.map((c) => ({
      kind: 'javascript-module' as const,
      path: options.module ? options.module(c.file) : c.file,
      declarations: [
        {
          kind: 'class' as const,
          name: c.name,
          ...(options.tagPrefix
            ? { tagName: `${options.tagPrefix}-${kebab(c.name)}`, customElement: true }
            : {}),
          ...(c.description ? { description: c.description } : {}),
          ...(c.deprecated !== undefined ? { deprecated: c.deprecated || true } : {}),
          attributes: [
            ...c.variants.map((v) => ({
              name: v.name,
              type: { text: v.values.map((x) => JSON.stringify(x)).join(' | ') },
              default: JSON.stringify(v.default),
              description: `One of ${v.values.join(', ')}.`,
            })),
            ...(options.props?.[c.name] ?? []).map((p) => ({
              name: kebab(p.name),
              type: { text: p.type === 'unknown' ? 'unknown' : p.type },
              default: p.default === undefined ? '' : JSON.stringify(p.default),
              description:
                p.type === 'array' || p.type === 'object'
                  ? `Set as a property, or as JSON in the attribute.`
                  : p.type === 'boolean'
                    ? 'On when the attribute is present.'
                    : '',
            })),
          ],
          events: Object.entries(c.events).map(([name, description]) => ({ name, description })),
          // The default slot has the empty name in this format.
          slots: Object.entries(c.slots).map(([name, description]) => ({
            name: name === 'default' ? '' : name,
            description,
          })),
          cssParts: c.parts.map((name) => ({ name, description: `The ${name} part.` })),
          cssStates: c.states.map((name) => ({ name, description: `The ${name} state.` })),
        },
      ],
      exports: [
        {
          kind: 'js' as const,
          name: c.name,
          declaration: { name: c.name, module: options.module ? options.module(c.file) : c.file },
        },
      ],
    })),
  }
}
